package io.github.nbplugins.kotlin.nbm.projectwizard

import com.intellij.ide.starters.local.generator.AssetsProcessor
import com.intellij.ide.starters.local.generator.AssetsProcessorImpl
import com.intellij.mock.MockApplication
import com.intellij.openapi.application.ApplicationManager
import org.jetbrains.kotlin.log.KotlinLogger
import org.jetbrains.kotlin.tools.projectWizard.compatibility.DependencyVersionStore
import org.jetbrains.kotlin.tools.projectWizard.compatibility.GradleToPluginsCompatibilityStore
import org.jetbrains.kotlin.tools.projectWizard.compatibility.KotlinWizardVersionStore
import org.jetbrains.kotlin.tools.projectWizard.compatibility.kotlinWizardVersionState
import org.jetbrains.plugins.gradle.jvmcompat.WIZARD_DATA_IDE_VERSION

/**
 * Kotlin version written into every project generated by the New Project wizard.
 *
 * Must stay equal to the Analysis API / stdlib version bundled by the plugin, so that a
 * generated project's Kotlin plugin version matches the language level the IDE analyses it
 * with.
 */
const val GENERATED_KOTLIN_VERSION: String = "2.3.21"

/**
 * Gradle version used for the wrapper of generated Gradle projects.
 *
 * Gradle 8.14.x, the wizard's original default, cannot run on JDK 25: its embedded Kotlin DSL
 * fails with `IllegalArgumentException: 25.0.2` from `JavaVersion.parse`. Gradle supports
 * running on JDK 25 since 9.1.0, and 9.3.0 is the newest version fully supported by Kotlin
 * Gradle Plugin [GENERATED_KOTLIN_VERSION] (7.6.3–9.3.0). Gradle 9 still runs on JDK 17+,
 * which is what NetBeans requires.
 */
const val GENERATED_GRADLE_VERSION: String = "9.3.0"

/**
 * Bootstraps the IDEA Kotlin New Project Wizard core in the standalone NetBeans environment.
 *
 * The wizard reads its configuration from IDEA application services
 * ([KotlinWizardVersionStore], [DependencyVersionStore],
 * [GradleToPluginsCompatibilityStore]) and writes files through [AssetsProcessor]. None of
 * them is declared in a plugin descriptor that the standalone `MockApplication` loads, so
 * they must be registered explicitly before anything touches the wizard's `Versions` or
 * `Dependencies` objects (their initializers resolve these services).
 *
 * The Kotlin version is injected into [KotlinWizardVersionStore] here: the wizard's built-in
 * default data pins the version shipped by the IntelliJ platform (2.3.10), while the plugin
 * must generate projects for [GENERATED_KOTLIN_VERSION].
 */
object ProjectWizardEnvironment {

    @Volatile
    private var registered = false

    /**
     * Registers the wizard services on the application, exactly once.
     *
     * Safe to call before the standalone application environment exists: the call is then a
     * no-op and a later call registers everything. Must be invoked before the first use of the
     * Kotlin New Project Wizard classes that read wizard versions or dependencies.
     */
    @Synchronized
    fun ensureRegistered() {
        if (registered) return
        val app = ApplicationManager.getApplication() as? MockApplication
        if (app == null) {
            KotlinLogger.INSTANCE.logInfo(
                "ProjectWizardEnvironment: application is not MockApplication yet; skipping registration"
            )
            return
        }

        if (app.getService(KotlinWizardVersionStore::class.java) == null) {
            app.registerService(KotlinWizardVersionStore::class.java, KotlinWizardVersionStore::class.java)
            val store = checkNotNull(app.getService(KotlinWizardVersionStore::class.java)) {
                "KotlinWizardVersionStore was not registered"
            }
            // `isDefault = false` and a matching IDE version make the store keep the injected
            // state instead of rebuilding its IDE defaults (see the patched
            // IdeVersionedDataStorage.loadState).
            store.loadState(
                kotlinWizardVersionState(GENERATED_KOTLIN_VERSION).apply {
                    isDefault = false
                    ideVersion = WIZARD_DATA_IDE_VERSION
                }
            )
            KotlinLogger.INSTANCE.logInfo(
                "Registered KotlinWizardVersionStore with Kotlin $GENERATED_KOTLIN_VERSION"
            )
        }

        if (app.getService(DependencyVersionStore::class.java) == null) {
            app.registerService(DependencyVersionStore::class.java, DependencyVersionStore::class.java)
        }

        if (app.getService(GradleToPluginsCompatibilityStore::class.java) == null) {
            app.registerService(GradleToPluginsCompatibilityStore::class.java, GradleToPluginsCompatibilityStore::class.java)
        }

        if (app.getService(AssetsProcessor::class.java) == null) {
            app.registerService(AssetsProcessor::class.java, AssetsProcessorImpl::class.java)
        }

        registered = true
    }
}
